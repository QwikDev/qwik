const SETUPS = ['single', 'tree', 'tree-context', 'conditional'] as const;
type Setup = (typeof SETUPS)[number];

const LEVELS: Record<Setup, number> = { single: 1, tree: 3, 'tree-context': 3, conditional: 3 };

const levelName = (level: number) => 'ABC'[level - 1];

const pascal = (value: string) =>
  value
    .split(/[^a-zA-Z0-9]/)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('');

const coreImports = (names: string[]) =>
  `import { ${[...new Set(names)].sort().join(', ')} } from '@qwik.dev/core';\n`;

const write = (path: string, content: string) => {
  const file = join(srcDir, path);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, header + content);
};

const result = () => `<output data-testid="result" data-done={out.value ? '' : undefined}>
        {out.value}
      </output>`;

const fixtureId = (setup: Setup, primitive: string) => `${setup}/${primitive}`;

const startsWhenVisible = (setup: Setup, primitive: string) =>
  setup !== 'conditional' && !!PRIMITIVES[primitive].startsWhenVisible;

const rootInput = (setup: Setup, primitive: string) =>
  `const input = useSignal(${startsWhenVisible(setup, primitive) ? 1 : 0});`;

const trigger = (setup: Setup, primitive: string) =>
  startsWhenVisible(setup, primitive)
    ? ''
    : `<button data-testid="trigger" onClick$={() => (input.value = 1)}>
        Run
      </button>
      `;

const writeSingle = (primitive: string) => {
  const { imports, code, step } = PRIMITIVES[primitive];
  write(
    `components/fixtures/single/${primitive}/index.tsx`,
    `${coreImports(['component$', 'useSignal', ...imports])}
export default component$(() => {
  ${rootInput('single', primitive)}${code('input')}
  return (
    <section class="fixture" data-fixture="${fixtureId('single', primitive)}">
      <h2>${fixtureId('single', primitive)}</h2>
      ${trigger('single', primitive)}${step ? `<span class="step">${step}</span>\n      ` : ''}${result()}
    </section>
  );
});
`
  );
};

const writeTree = (setup: 'tree' | 'tree-context', primitive: string) => {
  const { imports, code, step = '{out.value}' } = PRIMITIVES[primitive];
  const dir = `components/fixtures/${setup}/${primitive}`;
  const usesContext = setup === 'tree-context';
  const levels = LEVELS[setup];

  if (usesContext) {
    let contexts = `import { createContextId, type ReadonlySignal } from '@qwik.dev/core';\n`;
    for (let level = 1; level < levels; level++) {
      contexts += `\nexport const Level${level}Output = createContextId<ReadonlySignal<number>>('${fixtureId(setup, primitive)}/${level}');\n`;
    }
    write(`${dir}/contexts.ts`, contexts);
  }

  for (let level = 1; level <= levels; level++) {
    const isRoot = level === 1;
    const isLast = level === levels;
    const names = ['component$', ...imports];
    let lines = '';
    let props = '';
    if (isRoot) {
      names.push('useSignal');
      lines += `\n  ${rootInput(setup, primitive)}`;
    } else if (usesContext) {
      names.push('useContext');
      lines += `\n  const input = useContext(Level${level - 1}Output);`;
    } else {
      names.push('type ReadonlySignal');
      props = `<{ input: ReadonlySignal<number> }>`;
    }
    lines += code('input');
    if (usesContext && !isLast) {
      names.push('useContextProvider');
      lines += `\n  useContextProvider(Level${level}Output, out);`;
    }
    const contextImports: string[] = [];
    if (usesContext && !isRoot) {
      contextImports.push(`Level${level - 1}Output`);
    }
    if (usesContext && !isLast) {
      contextImports.push(`Level${level}Output`);
    }
    const childImport = isLast ? '' : `import Level${level + 1} from './level-${level + 1}';\n`;
    const contextImport = contextImports.length
      ? `import { ${contextImports.join(', ')} } from './contexts';\n`
      : '';
    const child = isLast
      ? result()
      : usesContext
        ? `<Level${level + 1} />`
        : `<Level${level + 1} input={out} />`;
    const params = isRoot || usesContext ? '()' : '({ input })';
    const body = `
  return (
    ${isRoot ? `<section class="fixture" data-fixture="${fixtureId(setup, primitive)}">` : '<div class="level">'}
      ${isRoot ? `<h2>${fixtureId(setup, primitive)}</h2>\n      ${trigger(setup, primitive)}` : ''}<span class="step">${levelName(level)}: ${step}</span>
      ${child}
    ${isRoot ? '</section>' : '</div>'}
  );`;
    write(
      `${dir}/${isRoot ? 'index' : `level-${level}`}.tsx`,
      `${coreImports(names)}${contextImport}${childImport}
export default component$${props}(${params} => {${lines}
${body}
});
`
    );
  }
};

