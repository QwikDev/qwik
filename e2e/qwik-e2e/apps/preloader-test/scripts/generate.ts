const routes: { group: string; href: string; label: string }[] = [];

const writeMatrix = () => {
  for (const setup of SETUPS) {
    rmSync(join(srcDir, `components/fixtures/${setup}`), { recursive: true, force: true });
    rmSync(join(srcDir, `routes/${setup}`), { recursive: true, force: true });
    for (const primitive of Object.keys(PRIMITIVES)) {
      if (setup === 'single') {
        writeSingle(primitive);
      } else if (setup === 'conditional') {
        writeConditional(primitive);
      } else {
        writeTree(setup, primitive);
      }
      writeRoute(
        `${setup}/${primitive}`,
        `~/components/fixtures/${setup}/${primitive}`,
        fixtureId(setup, primitive),
        startsWhenVisible(setup, primitive)
      );
      routes.push({ group: setup, href: `/${setup}/${primitive}/`, label: primitive });
    }
  }
};

